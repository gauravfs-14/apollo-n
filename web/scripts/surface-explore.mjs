// Free exploration + AR overlay screenshots. Usage: node scripts/surface-explore.mjs [outdir]
import { chromium } from "playwright";
const out = process.argv[2] ?? "/tmp/explore";
const browser = await chromium.launch({ headless: true, args: ["--use-angle=metal", "--mute-audio", "--enable-gpu", "--ignore-gpu-blocklist"] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on("pageerror", (e) => console.log("pageerror", e.message));
await page.addInitScript(() => localStorage.setItem("apollo.quality", "high"));
await page.goto(`http://localhost:3000/play/DEV-X${Date.now() % 1000000}?mode=solo&phase=surface&finale=16`, { waitUntil: "load" });
await page.waitForFunction(() => window.__surface?.rt && window.__surface.rt.exiting === false, null, { timeout: 90000 });
await page.waitForTimeout(500);
await page.getByRole("button", { name: /Explore the Moon/ }).waitFor({ timeout: 60000 });
await page.screenshot({ path: `${out}/1-choice.png` });
await page.getByRole("button", { name: /Explore the Moon/ }).click();
await page.waitForTimeout(1500);
const look = async (yaw, pitch, name, dist = 6.5) => {
  await page.evaluate(([y, p, d]) => { const r = window.__surface.rt; r.camYaw = y; r.camPitch = p; r.camDist = d; }, [yaw, pitch, dist]);
  await page.waitForTimeout(900);
  await page.screenshot({ path: `${out}/${name}.png` });
};
await page.evaluate(() => window.__surface.rt.pos.set(6, 8, 17));
await page.waitForTimeout(1200);
await look(-2.78, 0.2, "2-lander-far", 7);
await look(-2.2, 0.15, "3-lander-side", 7);
await page.keyboard.press("KeyE");
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/4-detail.png` });
await page.keyboard.press("KeyE");
await look(2.35, 0.08, "5-sun", 9);
await look(4.0, 0.2, "6-earth", 9);
await page.getByRole("button", { name: "Atlas" }).click();
await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/8-atlas.png` });
await page.getByRole("button", { name: /Apollo 15/ }).click();
await page.waitForTimeout(1200);
await page.screenshot({ path: `${out}/7-bearing.png` });
await page.keyboard.press("KeyE");
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/9-heritage-detail.png` });
await browser.close();
